//! A 5×7 bitmap font, embedded in the binary.
//!
//! The graph needs axis numbers and track names, and pulling in a font rasteriser (or asking
//! three different platforms for a system font) to draw "1k" and "-24" would be a poor trade.
//! A fixed 5×7 cell integer-scales cleanly, which is exactly what a resizable graph wants:
//! at 2× every stem is 2 px, with no hinting and no blur.
//!
//! Glyphs are column-major, one byte per column, bit 0 at the top.

/// Width of a glyph cell in pixels.
pub const GLYPH_W: usize = 5;

/// Height of a glyph cell in pixels.
pub const GLYPH_H: usize = 7;

/// Horizontal step from one glyph's origin to the next, at scale 1.
pub const ADVANCE: usize = GLYPH_W + 1;

/// First character in the table.
const FIRST: u8 = 0x20;

