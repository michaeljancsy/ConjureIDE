/// Column bitmaps for `ch`. Anything outside printable ASCII renders as `?`, so a host that
/// hands us an accented track name draws placeholders instead of nothing.
pub fn glyph(ch: char) -> &'static [u8; GLYPH_W] {
    let b = if ch.is_ascii() { ch as u8 } else { b'?' };
    let idx = b.wrapping_sub(FIRST) as usize;
    GLYPHS.get(idx).unwrap_or(&GLYPHS[(b'?' - FIRST) as usize])
}

/// Rendered width of `text` in pixels at `scale`. The trailing inter-glyph gap is not counted.
pub fn text_width(text: &str, scale: usize) -> usize {
    let n = text.chars().count();
    if n == 0 {
        0
    } else {
        (n * ADVANCE - 1) * scale
    }
}

/// Rendered height in pixels at `scale`.
pub fn text_height(scale: usize) -> usize {
    GLYPH_H * scale
}

/// Truncates `text` so it renders no wider than `max_px`, appending "…" (as `~`) when it had
/// to cut. Track names in a narrow legend need this.
pub fn elide(text: &str, max_px: usize, scale: usize) -> String {
    if text_width(text, scale) <= max_px {
        return text.to_string();
    }
    let cell = ADVANCE * scale;
    if max_px < cell {
        return String::new();
    }
    let fits = max_px / cell;
    if fits <= 1 {
        return String::new();
    }
    let mut s: String = text.chars().take(fits - 1).collect();
    s.push('~');
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    fn set_pixels(ch: char) -> u32 {
        glyph(ch).iter().map(|c| (c & 0x7f).count_ones()).sum()
    }

    #[test]
    fn space_is_blank_and_letters_are_not() {
        assert_eq!(set_pixels(' '), 0);
        for ch in "ABCXYZabcxyz0189".chars() {
            assert!(set_pixels(ch) > 0, "{ch} rendered blank");
        }
    }

    #[test]
    fn every_glyph_fits_the_cell() {
        // Bit 7 is outside the 7-row cell; a stray one there would bleed into the next line.
        for (i, g) in GLYPHS.iter().enumerate() {
            for (col, byte) in g.iter().enumerate() {
                assert_eq!(
                    byte & 0x80,
                    0,
                    "glyph {} column {col} sets a pixel outside the 7-row cell",
                    (FIRST + i as u8) as char
                );
            }
        }
    }

    #[test]
    fn the_table_covers_printable_ascii() {
        assert_eq!(GLYPHS.len(), (0x7E - 0x20 + 1) as usize);
        // The last entry must really be '~' — an off-by-one in the table would shift
        // every glyph and silently render mojibake.
        assert_eq!(glyph('~'), &[0x08, 0x04, 0x08, 0x10, 0x08]);
        assert_eq!(glyph('0'), &[0x3E, 0x51, 0x49, 0x45, 0x3E]);
        assert_eq!(glyph('A'), &[0x7E, 0x11, 0x11, 0x11, 0x7E]);
        assert_eq!(glyph('a'), &[0x20, 0x54, 0x54, 0x54, 0x78]);
    }

    #[test]
    fn dense_letters_have_more_ink_than_sparse_ones() {
        // A cheap sanity check that the table isn't scrambled.
        assert!(set_pixels('M') > set_pixels('I'));
        assert!(set_pixels('W') > set_pixels('.'));
        assert!(set_pixels('8') > set_pixels('1'));
    }

    #[test]
    fn non_ascii_falls_back_to_a_placeholder() {
        assert_eq!(glyph('é'), glyph('?'));
        assert_eq!(glyph('ド'), glyph('?'));
    }

    #[test]
    fn text_width_scales_linearly() {
        assert_eq!(text_width("", 1), 0);
        assert_eq!(text_width("A", 1), GLYPH_W);
        assert_eq!(text_width("AB", 1), GLYPH_W * 2 + 1);
        assert_eq!(text_width("AB", 2), (GLYPH_W * 2 + 1) * 2);
    }

    #[test]
    fn elide_respects_the_budget() {
        let long = "Very Long Track Name";
        for max in [0usize, 5, 12, 40, 80, 400] {
            let out = elide(long, max, 1);
            assert!(
                text_width(&out, 1) <= max.max(0),
                "{out:?} ({} px) exceeded {max} px",
                text_width(&out, 1)
            );
        }
    }

    #[test]
    fn elide_leaves_short_text_alone() {
        assert_eq!(elide("Kick", 1000, 1), "Kick");
    }

    #[test]
    fn elide_marks_that_it_cut() {
        let out = elide("Very Long Track Name", 40, 1);
        assert!(out.ends_with('~'), "expected an elision marker, got {out:?}");
    }
}
